"""Build, flash and talk to the e-paper display (firmware/Display). Python 3 stdlib; Pillow only for `frame`.

  python -I tools/fw.py build [--build N] [--repo OWNER/NAME]   compile to firmware/build/
  python -I tools/fw.py usb   [--port COM6]                     flash over USB (also writes the partition table)
  python -I tools/fw.py lan   [--host epaper.local]             upload the built .bin over Wi-Fi (POST /update)
  python -I tools/fw.py status [--host ...]                     print the board's status JSON
  python -I tools/fw.py set   key=value ... [--host ...]        change settings, e.g. updateUrl=https://...
  python -I tools/fw.py action check|install|clock|full|reboot  run a web-UI action
  python -I tools/fw.py frame IMAGE [--out f.bin] [--host ...]   convert any image to a 1-bit frame and/or push it
  python -I tools/fw.py manifest --build N --url URL --out DIR   write manifest.json for a built .bin (used by CI)

If the board has an admin password, set EPAPER_ADMIN_PASS in the environment (never in a file).
"""
import argparse, base64, hashlib, json, os, subprocess, sys, urllib.request, uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FW_DIR = ROOT / "firmware"
SKETCH = FW_DIR / "Display"
BUILD = FW_DIR / "build"
BIN = BUILD / "Display.ino.bin"
APP_SLOT = 0x1E0000            # matches firmware/Display/partitions.csv
W, H, FB_BYTES = 1360, 480, 81600


def build(args):
    repo = args.repo or os.environ.get("GITHUB_REPOSITORY", "")
    lines = ["// Generated by tools/fw.py. Do not edit or commit.", f"#define FW_BUILD {int(args.build)}"]
    if repo:
        url = f"https://github.com/{repo}/releases/download/ota/manifest.json"
        lines.append(f'#define DEFAULT_UPDATE_URL "{url}"')
    (SKETCH / "build_info.h").write_text("\n".join(lines) + "\n", encoding="utf-8")
    cmd = ["arduino-cli", "compile", "--profile", "xiao_c6",
           "--build-property", f"upload.maximum_size={APP_SLOT}",
           "--output-dir", str(BUILD), str(SKETCH)]
    print(" ".join(cmd), flush=True)
    subprocess.run(cmd, check=True, cwd=FW_DIR)
    print(f"built {BIN} ({BIN.stat().st_size:,} bytes), build {args.build}" + (f", updates from {repo}" if repo else ""))


def usb(args):
    if not BIN.exists():
        sys.exit("build first: python -I tools/fw.py build")
    cmd = ["arduino-cli", "upload", "--profile", "xiao_c6", "-p", args.port, "--input-dir", str(BUILD), str(SKETCH)]
    print(" ".join(cmd), flush=True)
    subprocess.run(cmd, check=True, cwd=FW_DIR)


def _request(host, path, data=None, headers=None, method=None, timeout=60):
    req = urllib.request.Request(f"http://{host}{path}", data=data, headers=headers or {}, method=method)
    pw = os.environ.get("EPAPER_ADMIN_PASS")
    if pw:
        req.add_header("Authorization", "Basic " + base64.b64encode(f"admin:{pw}".encode()).decode())
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return r.read()


def _multipart(field, filename, payload):
    b = uuid.uuid4().hex
    body = (f"--{b}\r\nContent-Disposition: form-data; name=\"{field}\"; filename=\"{filename}\"\r\n"
            f"Content-Type: application/octet-stream\r\n\r\n").encode() + payload + f"\r\n--{b}--\r\n".encode()
    return body, {"Content-Type": f"multipart/form-data; boundary={b}"}


def lan(args):
    data = Path(args.file or BIN).read_bytes()
    body, hdr = _multipart("firmware", "Display.ino.bin", data)
    print(f"uploading {len(data):,} bytes to {args.host} ...", flush=True)
    print(_request(args.host, "/update", body, hdr, timeout=180).decode())


def status(args):
    print(json.dumps(json.loads(_request(args.host, "/api/status")), indent=1))


def set_(args):
    s = {}
    for kv in args.pairs:
        k, _, v = kv.partition("=")
        s[k] = int(v) if v.isdigit() else ({"true": True, "false": False}.get(v, v))
    print(_request(args.host, "/api/settings", json.dumps(s).encode(), {"Content-Type": "application/json"}).decode())


def action(args):
    print(_request(args.host, f"/api/action?do={args.name}", b"", method="POST", timeout=180).decode())


def to_frame(path, dither=True):
    from PIL import Image, ImageOps
    im = ImageOps.exif_transpose(Image.open(path)).convert("L")
    im = ImageOps.fit(im, (W, H), Image.LANCZOS)                   # cover + center-crop to 1360x480
    im = im.convert("1", dither=Image.FLOYDSTEINBERG if dither else Image.NONE)
    # PIL "1": 0 = black, MSB-first. Panel: 1 = black. Invert the bits.
    return bytes(b ^ 0xFF for b in im.tobytes())


def frame(args):
    fb = to_frame(args.image, not args.no_dither)
    assert len(fb) == FB_BYTES
    if args.out:
        Path(args.out).write_bytes(fb); print(f"wrote {args.out}")
    if args.host and not args.out or args.push:
        body, hdr = _multipart("frame", "frame.bin", fb)
        print(_request(args.host, "/api/fb", body, hdr).decode())


def manifest(args):
    data = Path(args.file or BIN).read_bytes()
    m = {"build": int(args.build), "version": f"{args.version}+{args.build}", "url": args.url,
         "size": len(data), "sha256": hashlib.sha256(data).hexdigest()}
    out = Path(args.out); out.mkdir(parents=True, exist_ok=True)
    (out / "manifest.json").write_text(json.dumps(m, indent=1) + "\n", encoding="utf-8")
    print(json.dumps(m))


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    host = os.environ.get("EPAPER_HOST", "epaper.local")
    b = sub.add_parser("build"); b.add_argument("--build", default=0, type=int); b.add_argument("--repo"); b.set_defaults(f=build)
    u = sub.add_parser("usb"); u.add_argument("--port", default="COM6"); u.set_defaults(f=usb)
    l = sub.add_parser("lan"); l.add_argument("--host", default=host); l.add_argument("--file"); l.set_defaults(f=lan)
    s = sub.add_parser("status"); s.add_argument("--host", default=host); s.set_defaults(f=status)
    st = sub.add_parser("set"); st.add_argument("pairs", nargs="+"); st.add_argument("--host", default=host); st.set_defaults(f=set_)
    a = sub.add_parser("action"); a.add_argument("name"); a.add_argument("--host", default=host); a.set_defaults(f=action)
    f = sub.add_parser("frame"); f.add_argument("image"); f.add_argument("--out"); f.add_argument("--host", default=host)
    f.add_argument("--push", action="store_true", help="push even when --out is given"); f.add_argument("--no-dither", action="store_true"); f.set_defaults(f=frame)
    m = sub.add_parser("manifest"); m.add_argument("--build", required=True); m.add_argument("--url", required=True)
    m.add_argument("--out", required=True); m.add_argument("--file"); m.add_argument("--version", default=_fw_version()); m.set_defaults(f=manifest)
    args = p.parse_args(); args.f(args)


def _fw_version():
    for line in (SKETCH / "config.h").read_text(encoding="utf-8").splitlines():
        if line.startswith("#define FW_VERSION"):
            return line.split('"')[1]
    return "0"


if __name__ == "__main__":
    main()
